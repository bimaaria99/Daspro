public class ContohPenggunaanOperator {

    public static void main(String[] args) {
        int a = 10;
        int b = 5;
        int c = 2;

        System.out.println("Artimetika Operator");
        System.out.println("Bilangan a adalah : " + a);
        System.out.println("Bilangan b adalah : " + b);
        System.out.println("Bilangan c adalah : " + c);
        System.out.println("Hasil a + b + c = " + (a + b + c));
        System.out.println("Hasil a - b - c = " + (a - b - c));
        System.out.println("Hasil a * b * c = " + (a * b));
        System.out.println("Hasil a / b / c = " + (a / b));
        System.out.println("Hasil a % b % c = " + (a % b));
        System.out.println("Hasil a + b + c = " + (a+b*c));
        System.out.println("Hasil a - b - c = " + ((a+b)*c));
    }
    
}
